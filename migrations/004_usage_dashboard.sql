-- only) and not wired into a purge job here — fallback lookups are rare
-- enough (only reached on a contract-file miss) that row volume stays small.
-- If that stops being true, add a companion DELETE keyed on queried_at
-- alongside the existing retention sweep rather than inventing a second
-- schedule.
